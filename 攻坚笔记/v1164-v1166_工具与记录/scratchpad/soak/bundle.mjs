#!/usr/bin/env node
/* bundle.mjs — make ONE self-contained file out of fuzz.mjs + lib/*.mjs (for the repo: test_pk_room_fuzz_v1164.mjs).
 *   node bundle.mjs [outFile]      (default dist/test_pk_room_fuzz_v1164.mjs)
 * Each lib module becomes an IIFE that returns its exports; relative imports become destructuring.
 * In the bundle the repo directory defaults to the file's own directory (import.meta.url), profile defaults to ci. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(process.argv[2] || path.join(here, 'dist', 'test_pk_room_fuzz_v1164.mjs'));
const order = ['prng', 'world', 'ui', 'run', 'checks', 'scenario'];
const builtins = new Map();
let body = '';
for (const m of order) {
  let src = fs.readFileSync(path.join(here, 'lib', m + '.mjs'), 'utf8');
  const exported = [];
  src = src.replace(/^import\s+(\w+)\s+from\s+'(node:[\w/]+)';\s*$/mg, (all, name, mod) => { builtins.set(name, mod); return ''; });
  src = src.replace(/^import\s+\{[^}]*\}\s+from\s+'\.\/[\w]+\.mjs';\s*$/mg, '');
  src = src.replace(/^export\s+((?:async\s+)?(?:function\*?|class|const|let))\s+(\w+)/mg, (all, kw, name) => { exported.push(name); return kw + ' ' + name; });
  body += '\n/* ════════ lib/' + m + '.mjs ════════ */\nconst { ' + exported.join(', ') + ' } = (() => {\n' + src + '\nreturn { ' + exported.join(', ') + ' };\n})();\n';
}
let main = fs.readFileSync(path.join(here, 'fuzz.mjs'), 'utf8');
main = main.replace(/^#!.*\n/, '');
main = main.replace(/^import\s+(\w+)\s+from\s+'(node:[\w/]+)';\s*$/mg, (all, name, mod) => { builtins.set(name, mod); return ''; });
main = main.replace(/^import\s+\{[^}]*\}\s+from\s+'\.\/lib\/[\w]+\.mjs';\s*$/mg, '');
/* in the repo: no argument needed — the module sits next to this file; default profile ci */
main = main.replace("const opt = { profile: 'ci',", "const opt = { profile: 'ci', /* bundled */");
main = main.replace("if (!repoDir) usage(2);", "if (!repoDir) repoDir = path.dirname(fileURLToPath(import.meta.url));");
/* CI: no shrinking unless asked (failing seeds are printed; reproduce with --seed S --profile P) */
main = main.replace("const doShrink = opt.shrink == null ? true : opt.shrink;", "const doShrink = opt.shrink == null ? false : opt.shrink;");
builtins.set('{ fileURLToPath }', 'node:url');
let head = '#!/usr/bin/env node\n/* test_pk_room_fuzz_v1164.mjs — GENERATED by bundle.mjs from the soak harness (fuzz.mjs + lib/*.mjs). Do not edit by hand.\n'
  + ' * Randomized, seeded soak test of the online-battle protocol (hansen_pk_room_v1065.js) on a virtual clock:\n'
  + ' * N simulated phones (each a vm context with the REAL module), one fake CloudBase collection with real permission\n'
  + ' * semantics, eventual consistency, latency, faults, partitions, clock skew, an optional adversary; invariants I1–I10.\n'
  + ' *   node test_pk_room_fuzz_v1164.mjs [repoDir] [--profile ci] [--seeds N] [--seed S] [--spec file] …  (exit 0 = no violations) */\n';
for (const [name, mod] of builtins) head += 'import ' + name + " from '" + mod + "';\n";
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, head + body + '\n/* ════════ fuzz.mjs (CLI) ════════ */\n' + main);
console.log('wrote ' + out + ' (' + Math.round(fs.statSync(out).size / 1024) + ' KB)');
