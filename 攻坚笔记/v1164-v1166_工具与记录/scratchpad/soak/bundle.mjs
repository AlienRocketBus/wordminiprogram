#!/usr/bin/env node
/* bundle.mjs — make ONE self-contained file out of fuzz.mjs + lib/*.mjs (for the repo: test_pk_room_fuzz_v1164.mjs).
 *   node bundle.mjs [outFile]      (default dist/test_pk_room_fuzz_v1164.mjs)
 * Each lib module becomes an IIFE that returns its exports; relative imports become destructuring.
 * In the bundle the repo directory defaults to the file's own directory (import.meta.url), profile defaults to ci. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(process.argv[2] || path.join(here, 'dist', 'test_pk_room_fuzz_v1164.mjs'));
const order = ['prng', 'world', 'ui', 'ui_r1', 'run', 'checks', 'scenario'];
/* regression scenarios (one real bug each) embedded into the test: specs/regress/*.json = {name, bug, spec} */
const regDir = path.join(here, 'specs', 'regress');
const regress = fs.existsSync(regDir) ? fs.readdirSync(regDir).filter((f) => f.endsWith('.json')).sort().map((f) => JSON.parse(fs.readFileSync(path.join(regDir, f), 'utf8'))) : [];
const builtins = new Map();
let body = '';
for (const m of order) {
  let src = fs.readFileSync(path.join(here, 'lib', m + '.mjs'), 'utf8');
  const exported = [];
  src = src.replace(/^import\s+(\w+)\s+from\s+'(node:[\w/]+)';\s*$/mg, (all, name, mod) => { builtins.set(name, mod); return ''; });
  src = src.replace(/^import\s+\{[^}]*\}\s+from\s+'\.\/[\w]+\.mjs';\s*$/mg, '');
  src = src.replace(/^export\s+((?:async\s+)?(?:function\*?|class|const|let))\s+(\w+)/mg, (all, kw, name) => { exported.push(name); return kw + ' ' + name; });
  body += '\n/* ════════ lib/' + m + '.mjs ════════ */\nconst { ' + exported.join(', ') + ' } = (() => {\n' + src + '\nreturn { ' + exported.join(', ') + ' };\n})();\n';
}
let main = fs.readFileSync(path.join(here, 'fuzz.mjs'), 'utf8');
main = main.replace(/^#!.*\n/, '');
main = main.replace(/^import\s+(\w+)\s+from\s+'(node:[\w/]+)';\s*$/mg, (all, name, mod) => { builtins.set(name, mod); return ''; });
main = main.replace(/^import\s+\{[^}]*\}\s+from\s+'\.\/lib\/[\w]+\.mjs';\s*$/mg, '');
/* in the repo: no argument needed — the module sits next to this file; default profile ci */
main = main.replace("const opt = { profile: 'ci',", "const opt = { profile: 'ci', /* bundled */");
main = main.replace("if (!repoDir) usage(2);", "if (!repoDir) repoDir = __HSN_ROOT;");
main = main.replace("const REGRESS_SPECS = [];", "const REGRESS_SPECS = " + JSON.stringify(regress) + ";");
/* CI: no shrinking unless asked (failing seeds are printed; reproduce with --seed S --profile P) */
main = main.replace("const doShrink = opt.shrink == null ? true : opt.shrink;", "const doShrink = opt.shrink == null ? false : opt.shrink;");
builtins.set('{ fileURLToPath }', 'node:url');
let head = '#!/usr/bin/env node\n'
  + '/* test_pk_room_fuzz_v1164.mjs — GENERATED by bundle.mjs from the soak harness (fuzz.mjs + lib/*.mjs). Do not edit by hand.\n'
  + ' *\n'
  + ' * 在线对战（天梯 / 房间）协议的随机浸泡测试，虚拟时钟上跑，几十秒跑完几十小时的对局：\n'
  + ' *   · 每部「手机」是一个 vm 上下文，里面跑**真的** hansen_pk_room_v1065.js（只换掉网络：假 CloudBase 照真规矩办事 ——\n'
  + ' *     谁建的文档只有谁能改、_id 唯一、读有主从延迟、查询带 db.command、权限 legacy / rules 两种回法）；\n'
  + ' *   哪些是真代码、哪些是模型（重要）：\n'
  + ' *   · **真代码**：数据层 hansen_pk_room_v1065.js 原样运行 —— 匹配、进房、确认、抢答、补分、离场判定、清理，这里的结论是实打实的；\n'
  + ' *   · **模型**：界面（对战屏、等人屏、结算等待、天梯）是照 hansen_pk_room_ui_v1065.js / hansen_ladder_ui_v1108.js\n'
  + ' *     的控制流手抄的（lib/ui_r1.mjs，按 56b8146 写的），没有真页面、没有 DOM；界面上的几处修复按代码特征开关\n'
  + ' *     （loadUiFlags）。界面那一层的问题以真页面回归测试为准：test_room_fuzz_regress_cloud_v1164.mjs（R2/R3/R4/R10）。\n'
  + ' *     界面函数一变就打 WARNING —— 要回来对一遍手抄的模型（工具源码和说明：攻坚笔记/v1164-v1166_工具与记录/scratchpad/soak/README.md）；\n'
  + ' *   · 网络、云数据库（主从延迟、_id 唯一、权限两种回法）、手机钟、切后台 / 冻结、刷新、捣乱的人：都是模拟的。\n'
  + ' * 默认：ci 档 400 个种子 + 内嵌的回归场景（每个对应一个查实的真 bug，见 REGRESS_SPECS）。不联网，确定性（同一份代码跑两次结果一样）。\n'
  + ' *   node test_pk_room_fuzz_v1164.mjs [repoDir] [--profile ci] [--seeds N] [--seed S] [--spec file] [--no-regress] …  （退出码 0 = 没有问题）\n'
  + ' *   复现一个失败的种子：node test_pk_room_fuzz_v1164.mjs --profile ci --seed 137 --trace */\n'
  + 'const __HSN_ROOT = decodeURIComponent(new URL(\'.\', import.meta.url).pathname);   /* 仓库根目录跟着测试文件走（审查 TI-7） */\n';
for (const [name, mod] of builtins) head += 'import ' + name + " from '" + mod + "';\n";
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, head + body + '\n/* ════════ fuzz.mjs (CLI) ════════ */\n' + main);
console.log('wrote ' + out + ' (' + Math.round(fs.statSync(out).size / 1024) + ' KB)');
