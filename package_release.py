# These files should never be release inputs even when their current contents
# happen not to match a high-confidence secret signature.  Failing is safer
# than silently omitting a credential file and hiding a dirty source tree.
SENSITIVE_EXACT_NAMES = {
    ".env", ".npmrc", ".pypirc", ".netrc", "credentials", "credentials.json",
    "id_rsa", "id_ed25519", "known_hosts",
}
SENSITIVE_SUFFIXES = {".pem", ".key", ".p12", ".pfx", ".jks", ".keystore"}

# Deliberately narrow high-confidence signatures. Generic words such as
# "token" are not enough to reject a source archive.
SECRET_PATTERNS = (
    ("GitHub fine-grained token", re.compile(rb"github_pat_[A-Za-z0-9_]{20,}")),
    ("GitHub classic token", re.compile(rb"gh[opusr]_[A-Za-z0-9]{30,}")),
    ("OpenAI API key", re.compile(rb"sk-(?:proj-)?[A-Za-z0-9_-]{24,}")),
    ("AWS access key", re.compile(rb"AKIA[0-9A-Z]{16}")),
    ("Google API key", re.compile(rb"AIza[0-9A-Za-z_-]{30,}")),
    ("private key", re.compile(
        rb"-----BEGIN (?:RSA |EC |DSA |OPENSSH )?PRIVATE KEY-----"
    )),
)
SECRET_SCAN_EXT = {
    ".html", ".js", ".mjs", ".json", ".md", ".py", ".sh", ".txt",
    ".yml", ".yaml", ".toml", ".ini", ".cfg", ".conf", ".csv", ".xml",
    ".pem", ".key", "",
}

# Office documents are ZIP containers.  Scanning only the compressed outer
# bytes would miss credentials stored in document.xml, so inspect every member
# with strict limits before the original .docx bytes can enter the source ZIP.
OFFICE_CONTAINER_EXT = {".docx"}
OFFICE_MAX_MEMBERS = 10_000
OFFICE_MAX_UNCOMPRESSED = 256 * 1024 * 1024

# DOS epoch is the earliest date supported by the ZIP format. Permissions and
# timestamps therefore do not depend on checkout time or operating system.
ZIP_DATE_TIME = (1980, 1, 1, 0, 0, 0)


def _version(value: str) -> str:
    value = value.strip().lower().removeprefix("v")
    if not value.isdigit() or int(value) <= 0:
        raise argparse.ArgumentTypeError("version must be a positive integer (for example: 944)")
    return value


def _inside(path: Path, parent: Path) -> bool:
    try:
        path.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def _is_runtime_html(rel: PurePosixPath) -> bool:
    name = rel.name
    return name in DEPLOY_RUNTIME_HTML or name.startswith("island_")


def _looks_like_release_output(path: Path) -> bool:
    """Recognize old/custom output directories so their README is not sourced."""
    try:
        names = {child.name for child in path.iterdir() if child.is_file()}
    except OSError:
        return False
    return (
        "README.md" in names
        and any(
            name.startswith("单词大冒险_v")
            and name.endswith(("_可直接部署.zip", "_含贾维斯完整源码.zip"))
            for name in names
        )
    )


def _deploy_allowed(rel: PurePosixPath) -> bool:
    if rel.name in DEPLOY_EXCLUDE_FILES:
        return False
    if (len(rel.parts) == 1 and rel.name.startswith("_")
            and rel.name not in {"_frame.html", "_sw_upgrade_v944.html"}):
        return False
    if rel.as_posix() == "VERSION":
        return True
    # 🔴v1045: 这两个文件必须随部署包一起交付——
    #   cloudbaserc.json 让用户能用 `tcb hosting deploy` 一键上传
    #   （命令行会按扩展名自动贴对 Content-Type，从根上避免"打开变下载"）；
    #   部署说明写清了三种上传方式与判断方法。
    #   它们不是 .html/.js 等运行时资源，故不在 DEPLOY_ALLOWED_EXT 里，需显式放行。
    if rel.as_posix() in DEPLOY_EXTRA_FILES:
        return True
    suffix = rel.suffix.lower()
    if suffix not in DEPLOY_ALLOWED_EXT:
        return False
    if suffix == ".html" and not _is_runtime_html(rel):
        return False
    return True


def _sensitive_release_path(rel: PurePosixPath) -> bool:
    name = rel.name.lower()
    return (
        name in SENSITIVE_EXACT_NAMES
        or name.startswith(".env.")
        or rel.suffix.lower() in SENSITIVE_SUFFIXES
    )


def _iter_files(mode: str, out_dir: Path):
    """Yield ``(absolute_path, posix_archive_name)`` in stable order."""
    exclude_dirs = DEPLOY_EXCLUDE_DIRS if mode == "deploy" else SOURCE_EXCLUDE_DIRS
    out_inside_root = _inside(out_dir, ROOT)
    out_resolved = out_dir.resolve()

    for directory, dirs, files in os.walk(ROOT):
        directory_path = Path(directory)
        kept_dirs = []
        for name in sorted(dirs):
            candidate = directory_path / name
            if name in exclude_dirs or (mode == "deploy" and name.startswith(".")):
                continue
            if _looks_like_release_output(candidate):
                continue
            if out_inside_root and candidate.resolve() == out_resolved:
                continue
            kept_dirs.append(name)
        dirs[:] = kept_dirs

        for name in sorted(files):
            path = directory_path / name
            rel_path = path.relative_to(ROOT)
            rel = PurePosixPath(*rel_path.parts)
            if path.is_symlink() or not path.is_file():
                continue
            # A source ZIP contains the manifest generated for that ZIP.  When
            # the archive is later restored as a new release input, never feed
            # the old manifest back into the next archive: each output gets one
            # freshly generated SHA256SUMS member below.
            if rel.as_posix() == MANIFEST_NAME:
                continue
            if _sensitive_release_path(rel):
                raise RuntimeError(f"sensitive credential filename is not allowed in release input: {rel}")
            if out_inside_root and _inside(path, out_dir):
                continue
            if mode == "deploy":
                if name.startswith(".") or not _deploy_allowed(rel):
                    continue
            else:
                if rel.as_posix() in SOURCE_EXCLUDE_FILES:
                    continue
                if path.suffix.lower() in SOURCE_EXCLUDE_EXT:
                    continue
            yield path, rel.as_posix()


def _scan_secrets(files: list[tuple[Path, str]]) -> None:
    entries: list[tuple[str, bytes, str]] = []
    for path, arcname in files:
        if path.suffix.lower() not in SECRET_SCAN_EXT:
            continue
        try:
            entries.append((arcname, path.read_bytes(), path.suffix.lower()))
        except OSError as exc:
            raise RuntimeError(f"cannot scan {arcname}: {exc}") from exc
    _scan_secret_entries(entries)


def _scan_secret_entries(entries: list[tuple[str, bytes, str]]) -> None:
    findings: list[str] = []
    for arcname, data, suffix in entries:
        if suffix in OFFICE_CONTAINER_EXT:
            try:
                with zipfile.ZipFile(io.BytesIO(data), "r") as office:
                    members = [info for info in office.infolist() if not info.is_dir()]
                    if len(members) > OFFICE_MAX_MEMBERS:
                        raise RuntimeError(
                            f"office document has too many members: {arcname}"
                        )
                    total = sum(info.file_size for info in members)
                    if total > OFFICE_MAX_UNCOMPRESSED:
                        raise RuntimeError(
                            f"office document expands beyond safety limit: {arcname}"
                        )
                    for info in members:
                        if info.flag_bits & 0x1:
                            raise RuntimeError(
                                f"encrypted office member cannot be scanned: {arcname}!{info.filename}"
                            )
                        member_data = office.read(info)
                        for label, pattern in SECRET_PATTERNS:
                            if pattern.search(member_data):
                                findings.append(f"{arcname}!{info.filename} ({label})")
            except zipfile.BadZipFile as exc:
                raise RuntimeError(
                    f"office document cannot be inspected: {arcname}"
                ) from exc
            continue
        if suffix not in SECRET_SCAN_EXT:
            continue
        for label, pattern in SECRET_PATTERNS:
            if pattern.search(data):
                findings.append(f"{arcname} ({label})")
    if findings:
        raise RuntimeError("secret scan rejected release input: " + ", ".join(findings[:8]))


def _zip_info(name: str) -> zipfile.ZipInfo:
    info = zipfile.ZipInfo(name, ZIP_DATE_TIME)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.create_system = 3
    info.external_attr = (stat.S_IFREG | 0o644) << 16
    return info


def _manifest_bytes(entries: list[tuple[str, bytes]]) -> bytes:
    lines = [f"{hashlib.sha256(data).hexdigest()}  {name}" for name, data in entries]
    return ("\n".join(lines) + "\n").encode("utf-8")


_LOCAL_REF_RE = re.compile(
    rb"(?:src|href)\s*=\s*['\"]([^'\"#]+)['\"]", re.IGNORECASE
)


def _verify_deploy_dependencies(archive: zipfile.ZipFile, names: set[str]) -> None:
    """Verify every literal local HTML dependency exists in the deploy ZIP."""
    missing: list[str] = []
    unsafe: list[str] = []
    for page_name in sorted(name for name in names if name.endswith(".html")):
        parent = PurePosixPath(page_name).parent
        data = archive.read(page_name)
        for match in _LOCAL_REF_RE.finditer(data):
            raw = match.group(1).decode("utf-8", "replace").strip()
            if not raw or raw.startswith(("http://", "https://", "//", "data:", "javascript:")):
                continue
            clean = raw.split("?", 1)[0].split("#", 1)[0]
            if not clean:
                continue
            if clean.endswith("/"):
                prefix = clean.lstrip("./")
                if prefix and any(name.startswith(prefix) for name in names):
                    continue
            candidate = PurePosixPath(clean.lstrip("/")) if clean.startswith("/") else parent / clean
            parts: list[str] = []
            escaped = False
            for part in candidate.parts:
                if part in ("", "."):
                    continue
                if part == "..":
                    if not parts:
                        escaped = True
                        break
                    parts.pop()
                else:
                    parts.append(part)
            normalized = PurePosixPath(*parts).as_posix()
            if escaped:
                unsafe.append(f"{page_name} -> {raw}")
            elif normalized and normalized not in names:
                missing.append(f"{page_name} -> {normalized}")
    if unsafe:
        raise RuntimeError(f"deploy HTML contains path traversal references: {unsafe[:8]}")
    if missing:
        raise RuntimeError(f"deploy archive is missing literal runtime dependencies: {missing[:12]}")

    try:
        manifest = json.loads(archive.read("manifest.webmanifest"))
    except Exception as exc:
        raise RuntimeError(f"manifest.webmanifest is invalid JSON: {exc}") from exc
    manifest_refs = [manifest.get("start_url", "")]
    manifest_refs.extend(icon.get("src", "") for icon in manifest.get("icons", []))
    for ref in manifest_refs:
        normalized = str(ref).split("?", 1)[0].lstrip("./")
        if normalized and normalized not in names:
            raise RuntimeError(f"manifest.webmanifest references missing deploy file: {normalized}")

    sw = archive.read("sw_v944.js").decode("utf-8", "replace")
    shell_match = re.search(r"const\s+SHELL\s*=\s*\[(.*?)\];", sw, re.DOTALL)
    if not shell_match:
        raise RuntimeError("sw_v944.js does not expose a literal SHELL dependency list")
    shell_refs = re.findall(r"['\"]\.\/([^'\"?#]+)", shell_match.group(1))
    sw_missing = sorted(ref for ref in shell_refs if ref not in names)
    if sw_missing:
        raise RuntimeError(f"sw_v944.js SHELL references missing deploy files: {sw_missing[:12]}")


