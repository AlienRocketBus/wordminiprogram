# 设计铁则：纯函数(两次构建哈希必一致)；存疑不剥；每个产物过 node --check，
# 失败即 RuntimeError 拒绝出包(fail-closed)。vendor_* 与 JSON 型 script 原样跳过。
_MINIFY_SKIP_PREFIX = ("vendor_",)
_RE_BEFORE = set("{}(,=:;!&|?+-*%~^<>[\n")
_KW_BEFORE = {"return","typeof","case","in","of","new","delete","void","instanceof","do","else","yield","await"}

def _strip_js_comments_safe(src: str) -> str:
    """带 ${} 配对回弹的完整版：包一层花括号深度跟踪。"""
    # 用更直接的实现：逐字符+显式深度
    out, i, n = [], 0, len(src)
    st = ["code"]; depth = [0]
    last_sig = "\n"; last_word = ""
    def can_regex():
        return last_sig in _RE_BEFORE or last_word in _KW_BEFORE
    while i < n:
        c = src[i]; top = st[-1]
        if top == "code":
            if c == "/" and src.startswith("//", i):
                j = src.find("\n", i)
                if j < 0: i = n; break
                i = j; continue
            if c == "/" and src.startswith("/*", i):
                j = src.find("*/", i+2)
                if j < 0: out.append(src[i:]); i = n; break
                seg = src[i:j+2]
                out.append(seg if seg.startswith("/*!") else ("\n" if "\n" in seg else " "))
                i = j+2; continue
            if c == "/" and can_regex():
                out.append(c); i += 1; incls = False
                while i < n:
                    d = src[i]; out.append(d)
                    if d == "\\" and i+1 < n: out.append(src[i+1]); i += 2; continue
                    if d == "[": incls = True
                    elif d == "]": incls = False
                    elif (d == "/" and not incls) or d == "\n": i += 1; break
                    i += 1
                last_sig = "/"; last_word = ""; continue
            if c in ("'", '"'):
                out.append(c); i += 1
                while i < n:
                    d = src[i]; out.append(d)
                    if d == "\\" and i+1 < n: out.append(src[i+1]); i += 2; continue
                    i += 1
                    if d == c: break
                last_sig = c; last_word = ""; continue
            if c == "`":
                out.append(c); i += 1; st.append("tpl"); continue
            if c == "{":
                depth[-1] += 1
            elif c == "}":
                if depth[-1] == 0 and len(st) >= 2 and st[-2] == "tpl":
                    out.append(c); i += 1; st.pop(); continue   # 结束 ${}
                depth[-1] = max(0, depth[-1]-1)
            out.append(c)
            if not c.isspace():
                last_sig = c
                last_word = (last_word + c) if (c.isalnum() or c in "_$") else ""
            i += 1; continue
        if top == "tpl":
            if c == "\\" and i+1 < n:
                out.append(c); out.append(src[i+1]); i += 2; continue
            if c == "`":
                out.append(c); i += 1; st.pop(); continue
            if c == "$" and src.startswith("${", i):
                out.append("${"); i += 2; st.append("code"); depth.append(0)
                last_sig = "{"; last_word = ""; continue
            out.append(c); i += 1; continue
    return "".join(out)

def _tidy_lines(src: str) -> str:
    lines = [ln.rstrip() for ln in src.split("\n")]
    out, blank = [], 0
    for ln in lines:
        if ln == "":
            blank += 1
            if blank > 1: continue
        else:
            blank = 0
        out.append(ln)
    return "\n".join(out)

def _node_syntax_ok(code: str, label: str) -> None:
    import subprocess, tempfile, os
    node = shutil.which("node")
    if not node:
        raise RuntimeError("minify 需要 node 做语法闸门；当前环境未找到 node")
    with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False, encoding="utf-8") as f:
        f.write(code); tmp = f.name
    try:
        r = subprocess.run([node, "--check", tmp], capture_output=True, text=True)
        if r.returncode != 0:
            raise RuntimeError(f"minify 语法闸门失败: {label}: {r.stderr[:300]}")
    finally:
        os.unlink(tmp)

_SCRIPT_RE = re.compile(r"(<script\b[^>]*>)(.*?)(</script>)", re.S | re.I)
_STYLE_RE = re.compile(r"(<style\b[^>]*>)(.*?)(</style>)", re.S | re.I)
_HTML_COMMENT_RE = re.compile(r"<!--.*?-->", re.S)

def _strip_css_comments(css: str) -> str:
    out, i, n = [], 0, len(css)
    while i < n:
        c = css[i]
        if c == "/" and css.startswith("/*", i):
            j = css.find("*/", i+2)
            if j < 0: out.append(css[i:]); break
            i = j+2; continue
        if c in ("'", '"'):
            out.append(c); i += 1
            while i < n:
                d = css[i]; out.append(d)
                if d == "\\" and i+1 < n: out.append(css[i+1]); i += 2; continue
                i += 1
                if d == c: break
            continue
        out.append(c); i += 1
    return "".join(out)

def _minify_html_deploy(src: str, label: str) -> str:
    parts, pos = [], 0
    spans = []
    for m in _SCRIPT_RE.finditer(src): spans.append((m.start(), m.end(), m, "script"))
    for m in _STYLE_RE.finditer(src): spans.append((m.start(), m.end(), m, "style"))
    spans.sort()
    def outer(seg: str) -> str:
        seg = _HTML_COMMENT_RE.sub("", seg)
        return _tidy_lines(seg)
    for s, e, m, kind in spans:
        parts.append(outer(src[pos:s]))
        open_tag, body, close_tag = m.group(1), m.group(2), m.group(3)
        low = open_tag.lower()
        if kind == "script":
            if "json" in low or 'type="module"' in low or "src=" in low:
                parts.append(open_tag + body + close_tag)      # 外链/JSON/模块 原样
            else:
                mb = _tidy_lines(_strip_js_comments_safe(body))
                _node_syntax_ok(mb, f"{label}<inline-script>")
                parts.append(open_tag + mb + close_tag)
        else:
            parts.append(open_tag + _tidy_lines(_strip_css_comments(body)) + close_tag)
        pos = e
    parts.append(outer(src[pos:]))
    return "".join(parts)

def _minify_entry(arcname: str, data: bytes) -> bytes:
    name = PurePosixPath(arcname).name
    suffix = PurePosixPath(arcname).suffix.lower()
    if any(name.startswith(p) for p in _MINIFY_SKIP_PREFIX):
        return data
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return data
    if suffix == ".js":
        out = _tidy_lines(_strip_js_comments_safe(text))
        _node_syntax_ok(out, arcname)
        return out.encode("utf-8")
    if suffix == ".html":
        return _minify_html_deploy(text, arcname).encode("utf-8")
    return data

def _write_zip(target: Path, mode: str) -> tuple[int, int, str]:
    files = list(_iter_files(mode, target.parent))
    if not files:
        raise RuntimeError(f"{mode} archive would be empty")

    entries: list[tuple[str, bytes]] = []
    total = 0
    minify_saved = 0
    for path, arcname in files:
        data = path.read_bytes()
        if mode == "deploy":
            slim = _minify_entry(arcname, data)
            minify_saved += len(data) - len(slim)
            data = slim
        entries.append((arcname, data))
        total += len(data)
    if mode == "deploy" and minify_saved:
        print(f"      [minify] 部署产物瘦身 {minify_saved/1048576:.2f} MiB (源码保持可读)")
    entries.sort(key=lambda item: item[0])
    # Scan exactly the immutable byte strings that will be archived.  Reading
    # paths once for scanning and again for ZIP creation leaves a TOCTOU window
    # where a credential could appear between the two reads.
    _scan_secret_entries([
        (arcname, data, PurePosixPath(arcname).suffix.lower())
        for arcname, data in entries
    ])
    _scan_forbidden_text_colors(entries)
    _verify_hf7_runtime_contract(entries)
    manifest = _manifest_bytes(entries)

    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_DEFLATED,
                         compresslevel=9, strict_timestamps=True) as archive:
        for arcname, data in entries:
            archive.writestr(_zip_info(arcname), data, compress_type=zipfile.ZIP_DEFLATED,
                             compresslevel=9)
        archive.writestr(_zip_info(MANIFEST_NAME), manifest,
                         compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)

    with zipfile.ZipFile(target, "r") as archive:
        bad = archive.testzip()
        names = set(archive.namelist())
        if bad:
            raise RuntimeError(f"CRC verification failed: {bad}")
        required = {"index.html", "sw_v944.js", "manifest.webmanifest", "VERSION", MANIFEST_NAME}
        if mode == "source":
            required.update(SOURCE_REQUIRED_FILES)
            # Every root-level regression present in the verified tree must be
            # archived; adding a test and accidentally shipping an older source
            # allow-list would otherwise make the Jarvis ZIP incomplete.
            required.update(
                path.name for path in ROOT.glob("test_*") if path.is_file()
            )
        missing = sorted(required - names)
        if missing:
            raise RuntimeError(f"{mode} archive is missing required files: {missing}")
        forbidden_runtime = sorted(names & FORBIDDEN_RUNTIME_FILES)
        if forbidden_runtime:
            raise RuntimeError(
                f"{mode} archive contains obsolete backup runtime files: {forbidden_runtime}"
            )
        if mode == "deploy":
            forbidden = [
                name for name in names
                if name != MANIFEST_NAME and not _deploy_allowed(PurePosixPath(name))
            ]
            if forbidden:
                raise RuntimeError(f"deploy archive contains non-runtime files: {forbidden[:8]}")
            _verify_deploy_dependencies(archive, names)
        elif any(PurePosixPath(name).suffix.lower() == ".zip" for name in names):
            raise RuntimeError("source archive contains a nested ZIP")

        listed = archive.read(MANIFEST_NAME).decode("utf-8").splitlines()
        expected = _manifest_bytes([
            (name, archive.read(name)) for name in sorted(names - {MANIFEST_NAME})
        ]).decode("utf-8").splitlines()
        if listed != expected:
            raise RuntimeError(f"{mode} SHA256SUMS verification failed")

    digest = hashlib.sha256(target.read_bytes()).hexdigest()
    return len(entries) + 1, total + len(manifest), digest


def _promote_assets(pairs: list[tuple[Path, Path]], stage: Path,
                    *, fail_at: int | None = None, verify=None) -> None:
    """Promote all assets as one rollback-capable transaction.

    ``fail_at`` is a deterministic test hook (1-based promotion index). It is
    never supplied by production code and lets the regression suite prove that
    a failure after the first replacement restores the complete old set.
    """
    backups: list[tuple[Path, Path]] = []
    promoted: list[Path] = []
    try:
        for index, (_staged, final) in enumerate(pairs, 1):
            if final.exists():
                if not final.is_file():
                    raise RuntimeError(f"release asset path is not a file: {final}")
                backup = stage / f".previous-{index}-{final.name}"
                os.replace(final, backup)
                backups.append((final, backup))
        for index, (staged, final) in enumerate(pairs, 1):
            if fail_at == index:
                raise RuntimeError(f"injected promotion failure at asset {index}")
            os.replace(staged, final)
            promoted.append(final)
        # A staged archive can be valid and still be damaged while it is
        # promoted to the user-facing filesystem (for example by a short copy
        # on a mounted workspace).  Keep the previous three assets available
        # until the final paths have been reopened and verified.
        if verify is not None:
            verify()
    except Exception:
        rollback_errors: list[str] = []
        for final in reversed(promoted):
            try:
                final.unlink(missing_ok=True)
            except OSError as exc:
                rollback_errors.append(f"remove {final.name}: {exc}")
        for final, backup in reversed(backups):
            try:
                if final.exists():
                    final.unlink()
                os.replace(backup, final)
            except OSError as exc:
                rollback_errors.append(f"restore {final.name}: {exc}")
        if rollback_errors:
            raise RuntimeError("asset promotion failed and rollback was incomplete: "
                               + "; ".join(rollback_errors))
        raise


def _require_jarvis_pass(version: str) -> None:
    """🔴v1070：没跑贾维斯体检，不许出包。

    「每次改完都跑一遍贾维斯」这条规矩在 v1059~v1069 **连丢十版**——
    全靠人记得的流程，一定会忘。所以把它从"靠记性"变成"发版硬条件"：

      jarvis.py 体检通过 → 写下 .jarvis_pass.json（版本 + 时间 + 守卫指纹）
      package_release  → 打包前必须看到**当前版本**的有效凭证

    凭证里带守卫文件指纹：**守卫改了却没重跑，凭证同样作废**——
    否则会出现"用旧体检结论给新守卫背书"。
    应急可用 HANSEN_SKIP_JARVIS=1 跳过，但会在包里留下明显告警。
    """
    import json, hashlib
    if os.environ.get("HANSEN_SKIP_JARVIS") == "1":
        print("⚠️  HANSEN_SKIP_JARVIS=1 —— 跳过贾维斯体检检查（本次发布未经体检）")
        return
    rec = ROOT / ".jarvis_pass.json"
    if not rec.exists():
        raise RuntimeError(
            "拒绝出包：没有贾维斯体检凭证。请先运行  python3 jarvis.py  并确保通过。"
        )
    try:
        data = json.loads(rec.read_text(encoding="utf-8"))
    except Exception as e:
        raise RuntimeError(f"拒绝出包：体检凭证损坏（{e}），请重新运行 python3 jarvis.py")
    if str(data.get("version", "")) != str(version):
        raise RuntimeError(
            f"拒绝出包：体检凭证是 v{data.get('version')} 的，当前要打 v{version}。"
            f"请对当前版本重新运行 python3 jarvis.py"
        )
    gh = ""
    for f in ("hansen_guards_v1068.py", "check_resources.py", "hansen_bug_registry.py",
              "jarvis_selftest.py"):
        fp = ROOT / f
        if fp.exists():
            gh += hashlib.sha256(fp.read_bytes()).hexdigest()[:16]
    if data.get("guards") != hashlib.sha256(gh.encode()).hexdigest()[:24]:
        raise RuntimeError(
            "拒绝出包：守卫文件在体检之后被改动过，旧凭证不能给新守卫背书。"
            "请重新运行 python3 jarvis.py"
        )
    # 🔴v1097：校验凭证签名 —— 防止有人（或未来的我）手改 score/legacy
    #   把「既有问题不许变多」这一档架空。实测确认过：改之前伪造 score=100
    #   legacy=0 能直接打包通过。
    import hashlib as _h
    _base = '|'.join(str(data.get(k, '')) for k in ('version', 'guards', 'legacy', 'score'))
    _want = _h.sha256(('hansen-jarvis-v1097|' + _base).encode()).hexdigest()[:32]
    if data.get('sig') != _want:
        raise RuntimeError(
            "拒绝出包：体检凭证内容与签名不符（可能被手工改过）。"
            "请重新运行 python3 jarvis_gate.py")
    print(f"🧾 贾维斯体检凭证有效（v{data.get('version')} · {data.get('at')}"
          f" · 体检 {data.get('score','?')}/100）")


def package(version: str, out_dir: Path) -> list[Path]:
    canonical_version = _version((ROOT / "VERSION").read_text(encoding="utf-8"))
    _require_jarvis_pass(canonical_version)
    if version != canonical_version:
        raise RuntimeError(
            f"requested v{version} does not match canonical VERSION v{canonical_version}"
        )
    out_dir.mkdir(parents=True, exist_ok=True)
    deploy = out_dir / DEPLOY_NAME.format(version=version)
    source = out_dir / SOURCE_NAME.format(version=version)
    readme = out_dir / README_ASSET
    expected_names = {deploy.name, source.name, readme.name}

    unexpected = sorted(p.name for p in out_dir.iterdir() if p.name not in expected_names)
    if unexpected:
        raise RuntimeError(
            "release output directory must contain only this version's three assets; "
            f"unexpected entries: {unexpected}"
        )
    if not (ROOT / README_ASSET).is_file():
        raise RuntimeError("README.md is required for every release")

    # Build everything off to the side. Existing good assets remain untouched
    # if a read, secret scan, ZIP write, or verification fails.
    with tempfile.TemporaryDirectory(prefix="hansen-release-", dir=out_dir) as tmp_name:
        stage = Path(tmp_name)
        staged_deploy = stage / deploy.name
        staged_source = stage / source.name
        staged_readme = stage / readme.name

        print(f"[1/3] Building deployable archive: {deploy.name}")
        d_count, d_bytes, d_sha = _write_zip(staged_deploy, "deploy")
        print(f"      {d_count} files · {d_bytes / 1048576:.1f} MiB · sha256 {d_sha}")

        print(f"[2/3] Building source/Jarvis archive: {source.name}")
        s_count, s_bytes, s_sha = _write_zip(staged_source, "source")
        print(f"      {s_count} files · {s_bytes / 1048576:.1f} MiB · sha256 {s_sha}")

        print(f"[3/3] Staging release notes: {README_ASSET}")
        shutil.copyfile(ROOT / README_ASSET, staged_readme)
        for path in (staged_deploy, staged_source, staged_readme):
            if not path.is_file() or path.stat().st_size == 0:
                raise RuntimeError(f"staged release asset is missing or empty: {path.name}")

        def verify_promoted_assets() -> None:
            expected_digests = ((deploy, d_sha), (source, s_sha))
            for path, expected_digest in expected_digests:
                actual_digest = hashlib.sha256(path.read_bytes()).hexdigest()
                if actual_digest != expected_digest:
                    raise RuntimeError(
                        f"post-promotion SHA256 verification failed for {path.name}: "
                        f"expected {expected_digest}, got {actual_digest}"
                    )
                try:
                    with zipfile.ZipFile(path, "r") as archive:
                        bad = archive.testzip()
                except (OSError, zipfile.BadZipFile) as exc:
                    raise RuntimeError(
                        f"post-promotion ZIP verification failed for {path.name}: {exc}"
                    ) from exc
                if bad:
                    raise RuntimeError(
                        f"post-promotion CRC verification failed for {path.name}: {bad}"
                    )
            if readme.read_bytes() != (ROOT / README_ASSET).read_bytes():
                raise RuntimeError("post-promotion README verification failed")

        _promote_assets([
            (staged_deploy, deploy), (staged_source, source), (staged_readme, readme)
        ], stage, verify=verify_promoted_assets)

    actual_names = {p.name for p in out_dir.iterdir()}
    artifacts = [deploy, source, readme]
    if actual_names != expected_names or any(not p.is_file() for p in artifacts):
        raise RuntimeError(
            "release contract failed: output must contain exactly two ZIPs and README.md; "
            f"found {sorted(actual_names)}"
        )
    print("✅ Release contract verified: exactly 2 reproducible ZIPs + README.md")
    return artifacts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build two immutable release ZIPs and README")
    parser.add_argument("version", nargs="?", type=_version,
                        help="release version; defaults to VERSION")
    parser.add_argument("--out", type=Path,
                        default=Path(os.environ.get("HANSEN_RELEASE_OUT", "release-assets")),
                        help="output directory (default: HANSEN_RELEASE_OUT or ./release-assets)")
    args = parser.parse_args(argv)
    version = args.version or _version((ROOT / "VERSION").read_text(encoding="utf-8"))
    try:
        package(version, args.out.expanduser().resolve())
    except Exception as exc:
        print(f"❌ Packaging failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
